#include <iostream>
#include <iomanip>

using namespace std;

void printRow(unsigned short int value) {
    cout << setfill('0') << setw(5) << dec << value << " | ";

    for (unsigned int mask = 1u << 15; mask > 0; mask >>= 1) {
        cout << ((value & mask) ? '1' : '0');

        if (mask == (1u << 12) || mask == (1u << 8) || mask == (1u << 4)) {
            cout << ' ';
        }
    }
    cout << " | ";

    cout << setw(6) << oct << value << " | ";

    cout << setw(4) << hex << nouppercase << value << '\n';

    cout << dec << setfill(' ');
}

int main() {
    unsigned short int x;
    if (!(cin >> x)) {
        return 0;
    }

    printRow(x);

    x = static_cast<unsigned short int>(x + 1);
    printRow(x);

    return 0;
}


