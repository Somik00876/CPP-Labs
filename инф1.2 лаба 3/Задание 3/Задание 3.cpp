#include <iostream>
#include <string>

using namespace std;

string to_base(long long n, int p) {
    string sist = "0123456789abcdef";
    string res = "";
    while (n > 0) {
        res = sist[n % p] + res;
        n /= p;
    }
    return res;
}

int main() {
    int p;
    long long n, m;

    cin >> p >> n >> m;
    if (p < 2 || p > 16) {
        cout << "Error" << endl;
        return 1;
    }

    if (n < 0 || m < 0) {
        cout << "Error" << endl;
        return 1;
    }

    string str_n = to_base(n, p);
    string str_m = to_base(n, p);
    string str_sum = to_base(n + m, p);

    cout << n << "(10) + " << m << "(10) = " << str_n << "(" << p << ") + " << str_m << "(" << p << ") = " << str_sum << "(" << p << ")" << endl;
    
    return 0;
}

