#include <iostream>
#include <string>

using namespace std;

string num(int a) {
    string sist = "0123456789abcdef";
    string res = "";

    res += sist[(a / 256) % 16];
    res += sist[(a / 16) % 16];
    res += sist[a % 16];

    return res;
}

int main() {
    for (int i = 256; i <= 4095; i++) {
        if (i % 2 == 0) {
            continue;
        }

        string num_a = num(i);

        int zero_count = 0; 
        for (char c : num_a) {
            if (c == '0') {
                zero_count++;
            }
        }
        if (zero_count == 1) {
            cout << num_a << "(16) == " << i << "(10)" << endl;
        }
    }
    return 0;
}

